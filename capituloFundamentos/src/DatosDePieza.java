public class DatosDePieza {
    public static void main(String[] args) {
        String nombre = "Torre";
        char columna = 'a';
        int fila = 1;
        boolean esBlanca = true;
        double valor = 5.0;

        System.out.println("Pieza: " + nombre);
        System.out.println("Casilla: " + columna + fila);
        System.out.println("¿Es blanca? " + esBlanca);
        System.out.println("Valor: " + valor);
    }
}
